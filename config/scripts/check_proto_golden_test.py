from __future__ import annotations

import unittest

import check_proto_golden as gate

BASE = """# Generated by go test ./internal/tests/protocompat -update. Lines may be added, never removed.
enum anixops.forward.v1.Engine.ENGINE_GOST = 2
field anixops.forward.v1.Violation.code = 3 optional string
rpc anixops.forward.v1.ForwardControl.CreateRoute(anixops.forward.v1.CreateRouteRequest) returns (anixops.forward.v1.CreateRouteResponse)
field anix.agent.v1.Hello.protocol = 1 optional string
"""


class ProtoGoldenTest(unittest.TestCase):
    def test_additions_pass(self) -> None:
        head = BASE + "field anixops.forward.v1.Violation.route_id = 4 optional string\n"
        self.assertEqual([], gate.removed(BASE, head))

    def test_comments_and_order_do_not_matter(self) -> None:
        lines = [line for line in BASE.splitlines() if not line.startswith("#")]
        self.assertEqual([], gate.removed(BASE, "\n".join(reversed(lines))))

    def test_a_removed_forward_line_fails(self) -> None:
        head = BASE.replace("field anixops.forward.v1.Violation.code = 3 optional string\n", "")
        self.assertEqual(["field anixops.forward.v1.Violation.code = 3 optional string"], gate.removed(BASE, head))

    def test_a_changed_line_fails(self) -> None:
        head = BASE.replace("ENGINE_GOST = 2", "ENGINE_GOST = 7")
        self.assertEqual(["enum anixops.forward.v1.Engine.ENGINE_GOST = 2"], gate.removed(BASE, head))

    def test_a_removed_rpc_fails(self) -> None:
        head = "\n".join(line for line in BASE.splitlines() if not line.startswith("rpc "))
        self.assertEqual(1, len(gate.removed(BASE, head)))

    def test_a_draft_package_may_edit_its_lines(self) -> None:
        head = BASE.replace("ENGINE_GOST = 2", "ENGINE_GOST = 7")
        self.assertEqual([], gate.removed(BASE, head, frozenset({"anixops.forward.v1"})))
        other = BASE.replace("field anix.agent.v1.Hello.protocol = 1 optional string\n", "")
        self.assertEqual(1, len(gate.removed(BASE, other, frozenset({"anixops.forward.v1"}))))

    def test_forward_is_frozen(self) -> None:
        self.assertNotIn("anixops.forward.v1", gate.DRAFT_PACKAGES)
        self.assertEqual(frozenset(), gate.DRAFT_PACKAGES)

    def test_element_name(self) -> None:
        self.assertEqual("anixops.forward.v1.ForwardControl.CreateRoute",
                         gate.element_name("rpc anixops.forward.v1.ForwardControl.CreateRoute(x) returns (y)"))
        self.assertEqual("", gate.element_name("garbage"))

    def test_the_repository_golden_only_grew_against_itself(self) -> None:
        current = (gate.REPO_ROOT / gate.GOLDEN).read_text(encoding="utf-8")
        self.assertEqual([], gate.removed(current, current))
        self.assertEqual(0, gate.main(["--base", "HEAD"]) if gate.read_revision("HEAD") is not None else 0)


if __name__ == "__main__":
    unittest.main()
