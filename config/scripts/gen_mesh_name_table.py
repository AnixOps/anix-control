#!/usr/bin/env python3
"""Generate the character table of intranet name normalization.

The mesh normalizes names with the Unicode 15.1.0 character database
(network kernel spec section 15.9.2 item 5): which non-ASCII code points
are kept (general category L* or Nd) and the simple lowercase mapping.
Language libraries follow newer Unicode versions, so the panel and the
node kernel embed this one table instead; the kernel uses the same file.

Usage: gen_mesh_name_table.py UnicodeData.txt OUTPUT
UnicodeData.txt is https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt;
its SHA-256 is checked.
"""

import hashlib
import sys

VERSION = "15.1.0"
SHA256 = "2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86"


def main(source: str, output: str) -> None:
    data = open(source, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"{source}: SHA-256 {digest}, not the one of UnicodeData.txt {VERSION}")
    keep = []
    lower = []
    first = None
    for line in data.decode("utf-8").splitlines():
        fields = line.split(";")
        code = int(fields[0], 16)
        name, category, mapping = fields[1], fields[2], fields[13]
        kept = category.startswith("L") or category == "Nd"
        if name.endswith(", First>"):
            first = code
            continue
        start = first if name.endswith(", Last>") else code
        first = None
        if kept and code >= 0x80:
            if keep and keep[-1][1] == start - 1:
                keep[-1][1] = code
            else:
                keep.append([start, code])
        if mapping:
            lower.append((code, int(mapping, 16)))
    with open(output, "w", encoding="utf-8", newline="\n") as out:
        out.write(f"# Intranet name normalization table, Unicode {VERSION} (UnicodeData.txt SHA-256 {SHA256}).\n")
        out.write("# Generated by config/scripts/gen_mesh_name_table.py; do not edit.\n")
        out.write("# keep FIRST LAST: non-ASCII code points of category L* or Nd. lower FROM TO: simple lowercase mapping.\n")
        for start, end in keep:
            out.write(f"keep {start:04X} {end:04X}\n")
        for source_code, target in lower:
            out.write(f"lower {source_code:04X} {target:04X}\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
