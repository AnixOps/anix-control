// Package protocompat guards the wire compatibility of every AnixOps
// protobuf contract. The golden file lists each service method, message
// field and enum value with its number and type. Removing or changing a
// listed element breaks modules built against an older contract and always
// fails; additions fail until the golden file is regenerated with
//
//	go test ./internal/tests/protocompat -update
package protocompat

