// The official signing root changed (v4.2): the identity-platform
// installation of a Control that ran with the old root points at a release
// bound to a retired root, so nobody can log in. These tests drive
// BootstrapIdentityPlatformPackage the way cmd/server's bootstrapDatabase does
// on the first start with the new root, on SQLite and on PostgreSQL. Every key
// here is generated by the test; no release key appears anywhere.

type rotationKey struct {
	public  ed25519.PublicKey
	private ed25519.PrivateKey
}

func newRotationKey(t *testing.T) rotationKey {
	t.Helper()
	public, private, err := ed25519.GenerateKey(rand.Reader)
	require.NoError(t, err)
	return rotationKey{public: public, private: private}
}

func (k rotationKey) encoded() string     { return base64.StdEncoding.EncodeToString(k.public) }
func (k rotationKey) fingerprint() string { return PluginTrustRootFingerprint(k.public) }
func (k rotationKey) keyID() string       { return PluginTrustRootKeyID(k.public) }

// startControlWithRoot is the start of a Control configured with key's root:
// bootstrapDatabase makes the configured root the active one, then runs the
// identity bootstrap with the same key and the package directory.
func startControlWithRoot(db *gorm.DB, key rotationKey, bootstrapDir string) error {
	if _, err := EnsurePluginTrustRoot(db, key.public); err != nil {
		return err
	}
	return BootstrapIdentityPlatformPackage(db, key.encoded(), bootstrapDir)
}

// prepareRotationDB creates the kernel schema; withOperationLog adds the
// operation log table that cmd/server's schema migration creates before the
// bootstrap runs.
func prepareRotationDB(t *testing.T, db *gorm.DB, withOperationLog bool) {
	t.Helper()
	require.NoError(t, EnsureKernelSchema(db))
	if withOperationLog {
		require.NoError(t, db.AutoMigrate(&model.OperationLog{}))
	}
}

// seedIdentityUnderRoot is a Control that ran with key's root and the
// bootstrap package at version: the release is registered, the artifact
// stored and the installation healthy at generation.
func seedIdentityUnderRoot(t *testing.T, db *gorm.DB, key rotationKey, version string, generation int64) model.PluginInstallation {
	t.Helper()
	directory := writeBootstrapIdentityPlatformPackageVersion(t, key.private, version)
	require.NoError(t, startControlWithRoot(db, key, directory))
	require.NoError(t, db.Model(&model.PluginInstallation{}).
		Where("plugin_id = ? AND target = ?", "identity-platform", "control").
		Updates(map[string]any{"observed_version": version, "state": "healthy", "lifecycle_generation": generation}).Error)
	return loadIdentityInstallation(t, db)
}

// seedPluginUnderRoot registers another package under key and installs it
// healthy at generation 5.
func seedPluginUnderRoot(t *testing.T, db *gorm.DB, key rotationKey, pluginID, version string, mutate func(*PluginManifest)) model.PluginInstallation {
	t.Helper()
	pkg := signedTestPackage(t, key.private, pluginID, version, mutate)
	release, err := RegisterPluginRelease(db, pkg.ManifestJSON, pkg.Signature, key.public)
	require.NoError(t, err)
	_, err = StorePluginArtifact(db, release.ID, pkg.Artifact)
	require.NoError(t, err)
	installation := model.PluginInstallation{
		PluginID: pluginID, Target: "control", DesiredVersion: version, ObservedVersion: version,
		State: "healthy", Enabled: true, LifecycleGeneration: 5,
	}
	require.NoError(t, db.Create(&installation).Error)
	return installation
}

func loadIdentityInstallation(t *testing.T, db *gorm.DB) model.PluginInstallation {
	t.Helper()
	return loadInstallation(t, db, "identity-platform")
}

func loadInstallation(t *testing.T, db *gorm.DB, pluginID string) model.PluginInstallation {
	t.Helper()
	var installation model.PluginInstallation
	require.NoError(t, db.First(&installation, "plugin_id = ? AND target = ?", pluginID, "control").Error)
	return installation
}

func loadRelease(t *testing.T, db *gorm.DB, pluginID, version string) model.PluginRelease {
	t.Helper()
	var release model.PluginRelease
	require.NoError(t, db.First(&release, "plugin_id = ? AND version = ?", pluginID, version).Error)
	return release
}

func rotationAuditEntries(t *testing.T, db *gorm.DB) []model.OperationLog {
	t.Helper()
	var entries []model.OperationLog
	require.NoError(t, db.Where("module = ?", "kernel").Order("id").Find(&entries).Error)
	return entries
}

func countReleases(t *testing.T, db *gorm.DB, pluginID string) int64 {
	t.Helper()
	var count int64
	require.NoError(t, db.Model(&model.PluginRelease{}).Where("plugin_id = ?", pluginID).Count(&count).Error)
	return count
}

// captureStandardLog returns what the standard logger prints from now on.
func captureStandardLog(t *testing.T) *bytes.Buffer {
	t.Helper()
	var buffer bytes.Buffer
	previous := log.Writer()
	log.SetOutput(&buffer)
	t.Cleanup(func() { log.SetOutput(previous) })
	return &buffer
}

