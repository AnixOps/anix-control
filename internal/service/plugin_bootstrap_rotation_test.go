func runIdentityRootRotationSuite(t *testing.T, open func(*testing.T) *gorm.DB) {
	t.Run("a retired-root installation moves to the verified bootstrap release", func(t *testing.T) {
		testRotationMovesInstallation(t, open(t))
	})
	t.Run("the same root never upgrades a healthy installation", func(t *testing.T) {
		testRotationSameRootUntouched(t, open(t))
	})
	t.Run("a bootstrap package signed by a third key changes nothing", func(t *testing.T) {
		testRotationThirdKeyRefused(t, open(t))
	})
	t.Run("other packages are not touched", func(t *testing.T) {
		testRotationOtherPluginsUntouched(t, open(t))
	})
	t.Run("a second start is idempotent", func(t *testing.T) {
		testRotationIdempotent(t, open(t))
	})
	t.Run("a bootstrap release that is not newer is refused", func(t *testing.T) {
		testRotationNotNewerRefused(t, open)
	})
	t.Run("the same version signed by another root keeps its error", func(t *testing.T) {
		testRotationSameVersionOtherRoot(t, open(t))
	})
	t.Run("a disabled installation is not re-enabled", func(t *testing.T) {
		testRotationDisabledUntouched(t, open(t))
	})
	t.Run("an installation without a release row is left alone", func(t *testing.T) {
		testRotationMissingReleaseUntouched(t, open(t))
	})
	t.Run("the move is validated like an administrator update", func(t *testing.T) {
		testRotationValidatedLikeAdminUpdate(t, open(t))
	})
	t.Run("the audit write is part of the transaction", func(t *testing.T) {
		testRotationAuditFailureRollsBack(t, open(t))
	})
	t.Run("the new lifecycle generation is accepted by the migration ledger", func(t *testing.T) {
		testRotationMigrationLedger(t, open(t))
	})
}

func testRotationMovesInstallation(t *testing.T, db *gorm.DB) {
	prepareRotationDB(t, db, true)
	rootA, rootB := newRotationKey(t), newRotationKey(t)
	before := seedIdentityUnderRoot(t, db, rootA, "4.1.0", 3)
	lastError := "plugin host unavailable: verified artifact reference is unavailable"
	require.NoError(t, db.Model(&before).Updates(map[string]any{"state": "failed", "last_error": lastError}).Error)
	logs := captureStandardLog(t)

	directory := writeBootstrapIdentityPlatformPackageVersion(t, rootB.private, "4.2.0-rc.1")
	require.NoError(t, startControlWithRoot(db, rootB, directory))

	// The installation intent moved the way an administrator's update moves
	// it: new desired version, pending, a new lifecycle generation. The host
	// start, the migration run and the observed version are the lifecycle
	// worker's, which the restart reconciliation queues for the new generation.
	after := loadIdentityInstallation(t, db)
	require.Equal(t, before.ID, after.ID)
	require.Equal(t, "4.2.0-rc.1", after.DesiredVersion)
	require.Equal(t, "4.1.0", after.ObservedVersion)
	require.Equal(t, "4.1.0", after.PreviousVersion)
	require.Equal(t, "pending", after.State)
	require.True(t, after.Enabled)
	require.Nil(t, after.DisabledAt)
	require.EqualValues(t, 4, after.LifecycleGeneration)
	require.Equal(t, lastError, after.LastError, "the worker clears the error when the host starts")
	require.Equal(t, before.ConfigRevision, after.ConfigRevision)

	// Releases are immutable: the old one stays bound to the retired root and
	// the new one is bound to the active root and verifies under it.
	oldRelease := loadRelease(t, db, "identity-platform", "4.1.0")
	newRelease := loadRelease(t, db, "identity-platform", "4.2.0-rc.1")
	require.Equal(t, rootA.fingerprint(), oldRelease.TrustRootFingerprint)
	require.Equal(t, rootB.fingerprint(), newRelease.TrustRootFingerprint)
	_, err := VerifyStoredPluginRelease(db, oldRelease, rootB.public)
	require.ErrorIs(t, err, ErrPluginTrustRootRequired)
	_, err = VerifyStoredPluginRelease(db, newRelease, rootB.public)
	require.NoError(t, err)
	require.NoError(t, ValidatePluginInstallationPlan(db, newRelease, "control", true, after.ID))
	artifact, err := GetPluginArtifact(db, newRelease.ID)
	require.NoError(t, err)
	require.NotEmpty(t, artifact.Data)

	// Audited, naming both versions and both roots.
	entries := rotationAuditEntries(t, db)
	require.Len(t, entries, 1)
	require.Equal(t, "bootstrap_installation_update", entries[0].Action)
	require.Equal(t, "plugin_installation", entries[0].TargetType)
	require.NotNil(t, entries[0].TargetID)
	require.Equal(t, after.ID, *entries[0].TargetID)
	require.Equal(t, "system/bootstrap", entries[0].Username)
	require.Equal(t, 1, entries[0].Status)
	var content map[string]any
	require.NoError(t, json.Unmarshal([]byte(entries[0].Content), &content))
	require.Equal(t, "identity-platform", content["plugin_id"])
	require.Equal(t, "4.1.0", content["from_version"])
	require.Equal(t, "4.2.0-rc.1", content["to_version"])
	require.Equal(t, rootA.fingerprint(), content["from_trust_root_fingerprint"])
	require.Equal(t, rootB.fingerprint(), content["to_trust_root_fingerprint"])
	require.EqualValues(t, 3, content["from_lifecycle_generation"])
	require.EqualValues(t, 4, content["to_lifecycle_generation"])

	// Loud: one warning that names old and new versions and roots.
	printed := logs.String()
	require.Contains(t, printed, "WARNING")
	for _, fact := range []string{"identity-platform", "4.1.0", "4.2.0-rc.1", rootA.keyID(), rootB.keyID()} {
		require.Contains(t, printed, fact)
	}
}

func testRotationSameRootUntouched(t *testing.T, db *gorm.DB) {
	prepareRotationDB(t, db, true)
	rootA := newRotationKey(t)
	before := seedIdentityUnderRoot(t, db, rootA, "4.1.0", 3)
	logs := captureStandardLog(t)

	// The bootstrap package is newer and verifies, but the installed release
	// is bound to the active root: a bootstrap never silently upgrades.
	directory := writeBootstrapIdentityPlatformPackageVersion(t, rootA.private, "4.2.0")
	require.NoError(t, startControlWithRoot(db, rootA, directory))

	require.Equal(t, before, loadIdentityInstallation(t, db))
	require.EqualValues(t, 2, countReleases(t, db, "identity-platform"), "the bootstrap release is still registered")
	require.Empty(t, rotationAuditEntries(t, db))
	require.NotContains(t, logs.String(), "WARNING")
}

func testRotationThirdKeyRefused(t *testing.T, db *gorm.DB) {
	prepareRotationDB(t, db, true)
	rootA, rootB, rootC := newRotationKey(t), newRotationKey(t), newRotationKey(t)
	before := seedIdentityUnderRoot(t, db, rootA, "4.1.0", 3)
	_, err := EnsurePluginTrustRoot(db, rootB.public)
	require.NoError(t, err)

	// The configuration names root B; the package in the directory is signed
	// by a key nobody configured.
	directory := writeBootstrapIdentityPlatformPackageVersion(t, rootC.private, "4.2.0")
	err = BootstrapIdentityPlatformPackage(db, rootB.encoded(), directory)
	require.Error(t, err)
	require.ErrorContains(t, err, "verify identity bootstrap package")
	require.ErrorContains(t, err, "plugin signature verification failed")

	require.Equal(t, before, loadIdentityInstallation(t, db))
	require.EqualValues(t, 1, countReleases(t, db, "identity-platform"))
	require.Empty(t, rotationAuditEntries(t, db))
}

func testRotationOtherPluginsUntouched(t *testing.T, db *gorm.DB) {
	prepareRotationDB(t, db, true)
	rootA, rootB := newRotationKey(t), newRotationKey(t)
	seedIdentityUnderRoot(t, db, rootA, "4.1.0", 3)
	seedPluginUnderRoot(t, db, rootA, "knowledge", "4.1.0", nil)
	knowledgeBefore := loadInstallation(t, db, "knowledge")

	directory := writeBootstrapIdentityPlatformPackageVersion(t, rootB.private, "4.2.0")
	require.NoError(t, startControlWithRoot(db, rootB, directory))

	require.Equal(t, "4.2.0", loadIdentityInstallation(t, db).DesiredVersion)
	// knowledge still points at its old-root release: the operator imports
	// the other packages (docs/UPGRADE.md), the bootstrap never does.
	require.Equal(t, knowledgeBefore, loadInstallation(t, db, "knowledge"))
	knowledgeRelease := loadRelease(t, db, "knowledge", "4.1.0")
	require.Equal(t, rootA.fingerprint(), knowledgeRelease.TrustRootFingerprint)
	_, err := VerifyStoredPluginRelease(db, knowledgeRelease, rootB.public)
	require.ErrorIs(t, err, ErrPluginTrustRootRequired)
	require.EqualValues(t, 1, countReleases(t, db, "knowledge"))
	entries := rotationAuditEntries(t, db)
	require.Len(t, entries, 1)
	require.Contains(t, entries[0].Content, `"plugin_id":"identity-platform"`)
}

func testRotationIdempotent(t *testing.T, db *gorm.DB) {
	prepareRotationDB(t, db, true)
	rootA, rootB := newRotationKey(t), newRotationKey(t)
	seedIdentityUnderRoot(t, db, rootA, "4.1.0", 3)
	directory := writeBootstrapIdentityPlatformPackageVersion(t, rootB.private, "4.2.0")
	require.NoError(t, startControlWithRoot(db, rootB, directory))
	moved := loadIdentityInstallation(t, db)
	require.EqualValues(t, 4, moved.LifecycleGeneration)
	logs := captureStandardLog(t)

	// A restart before the worker ran, and one after it did (desired is
	// observed and healthy): neither moves anything or writes another entry.
	require.NoError(t, startControlWithRoot(db, rootB, directory))
	require.Equal(t, moved, loadIdentityInstallation(t, db))
	require.NoError(t, db.Model(&model.PluginInstallation{}).Where("id = ?", moved.ID).
		Updates(map[string]any{"observed_version": "4.2.0", "state": "healthy", "last_error": ""}).Error)
	healthy := loadIdentityInstallation(t, db)
	require.NoError(t, startControlWithRoot(db, rootB, directory))
	require.Equal(t, healthy, loadIdentityInstallation(t, db))

	require.Len(t, rotationAuditEntries(t, db), 1)
	require.EqualValues(t, 2, countReleases(t, db, "identity-platform"))
	require.NotContains(t, logs.String(), "WARNING")
}

func testRotationNotNewerRefused(t *testing.T, open func(*testing.T) *gorm.DB) {
	for _, test := range []struct {
		name      string
		installed string
		bootstrap string
	}{
		{name: "older", installed: "4.2.0", bootstrap: "4.1.0"},
		{name: "older prerelease", installed: "4.2.0", bootstrap: "4.2.0-rc.1"},
		{name: "same precedence", installed: "4.2.0", bootstrap: "4.2.0+rebuild"},
		{name: "not full semantic versions", installed: "20260101", bootstrap: "20260202"},
		{name: "shorthand versions", installed: "4.2", bootstrap: "4.3"},
	} {
		t.Run(test.name, func(t *testing.T) {
			db := open(t)
			prepareRotationDB(t, db, true)
			rootA, rootB := newRotationKey(t), newRotationKey(t)
			before := seedIdentityUnderRoot(t, db, rootA, test.installed, 3)
			logs := captureStandardLog(t)

			// A bootstrap package never moves an installation to a release that
			// is not provably newer; the start goes on (a rolled-back image
			// must still start) and says so.
			directory := writeBootstrapIdentityPlatformPackageVersion(t, rootB.private, test.bootstrap)
			require.NoError(t, startControlWithRoot(db, rootB, directory))

			require.Equal(t, before, loadIdentityInstallation(t, db))
			require.Empty(t, rotationAuditEntries(t, db))
			printed := logs.String()
			require.Contains(t, printed, "WARNING")
			require.Contains(t, printed, "not moved")
			require.Contains(t, printed, test.installed)
			require.Contains(t, printed, test.bootstrap)
			require.Contains(t, printed, rootA.keyID())
			require.Contains(t, printed, rootB.keyID())
		})
	}
}

