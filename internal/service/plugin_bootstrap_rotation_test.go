func testRotationAuditFailureRollsBack(t *testing.T, db *gorm.DB) {
	// Without the operation log table the audit write fails: the move must
	// not survive as an unaudited change, and the start must say so.
	prepareRotationDB(t, db, false)
	rootA, rootB := newRotationKey(t), newRotationKey(t)
	before := seedIdentityUnderRoot(t, db, rootA, "4.1.0", 3)

	directory := writeBootstrapIdentityPlatformPackageVersion(t, rootB.private, "4.2.0")
	err := startControlWithRoot(db, rootB, directory)
	require.Error(t, err)
	require.ErrorContains(t, err, "audit")
	require.Equal(t, before, loadIdentityInstallation(t, db))
}

func testRotationMigrationLedger(t *testing.T, db *gorm.DB) {
	prepareRotationDB(t, db, true)
	rootA, rootB := newRotationKey(t), newRotationKey(t)
	seedIdentityUnderRoot(t, db, rootA, "4.1.0", 3)

	// The ledger holds a verified run of the old version at generation 3.
	run, err := BeginPackageMigration(db, model.PackageMigrationRun{
		PackageID: "identity-platform", PackageVersion: "4.1.0", Generation: 3,
		MigrationID: "identity-index", MigrationChecksum: "checksum-4.1.0",
		BeforeSchemaVersion: noPreviousSchemaVersion, AfterSchemaVersion: "4.1.0",
	})
	require.NoError(t, err)
	_, err = RecordMigrationCheckpoint(db, run.ID, PackageMigrationCheckpoint{
		OpaqueCheckpoint: "complete", ValidationDigest: "digest-4.1.0", Complete: true,
	})
	require.NoError(t, err)
	verifiedAt := time.Now().UTC()
	require.NoError(t, db.Model(&model.PackageMigrationRun{}).Where("id = ?", run.ID).Updates(map[string]any{
		"health_lease_id": "lease-3", "health_generation": uint64(3), "health_verified_at": &verifiedAt,
	}).Error)
	_, err = RecordPackageValidation(db, model.PackageValidationResult{MigrationRunID: run.ID})
	require.NoError(t, err)

	directory := writeBootstrapIdentityPlatformPackageVersion(t, rootB.private, "4.2.0")
	require.NoError(t, startControlWithRoot(db, rootB, directory))
	moved := loadIdentityInstallation(t, db)

	// The host start of the new release runs under the new generation, which
	// the ledger accepts after the verified run of generation 3. The old
	// generation cannot be reused for another version: a column write that
	// kept it would fail the migration of the host it moved to.
	next := model.PackageMigrationRun{
		PackageID: "identity-platform", PackageVersion: "4.2.0", Generation: uint64(moved.LifecycleGeneration), // #nosec G115 -- the move leaves a positive generation.
		MigrationID: "identity-index-next", MigrationChecksum: "checksum-4.2.0",
		BeforeSchemaVersion: "4.1.0", AfterSchemaVersion: "4.2.0", BackupReference: "operator-managed:identity-platform",
	}
	started, err := BeginPackageMigration(db, next)
	require.NoError(t, err)
	require.NotNil(t, started.PreviousGenerationID)
	reused := next
	reused.Generation = 3
	_, err = BeginPackageMigration(db, reused)
	require.ErrorIs(t, err, ErrPackageMigrationImmutable)
}
